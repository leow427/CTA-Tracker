"""Builds src/fonts.cpp: Nunito glyphs rasterized by headless Chrome, as the mockup's canvas draws them.

Run from anywhere: python3 tools/font_build.py (needs Google Chrome and network access for Google Fonts).
"""
import html, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'

def main():
    page = 'file://' + os.path.join(HERE, 'font_build.html')
    dom = subprocess.run([CHROME, '--headless=new', '--disable-gpu', '--virtual-time-budget=20000', '--dump-dom', page],
                         capture_output=True, text=True, check=True).stdout
    m = re.search(r'<pre id="fonts_out">(.*?)</pre>', dom, re.S)
    if not m:
        sys.exit('font_build: Chrome produced no glyphs (are Google Fonts reachable?)')
    fonts = json.loads(html.unescape(m.group(1)))
    out = ['// Generated by tools/font_build.py from tools/font_build.html. Do not edit; rerun it.',
           '#include "fonts.h"', '', 'namespace ui {', '']
    table = []
    for f in fonts:
        tag = f"w{f['weight']}_{f['size']}"
        bitmap, glyphs = [], []
        for g in sorted(f['glyphs'], key=lambda g: g['cp']):
            glyphs.append(f"{{{g['cp']}, {round(g['adv'] * 16)}, {g['x']}, {g['y']}, {g['w']}, {g['h']}, {len(bitmap)}}}")
            bitmap += g['a']
        out.append(f'static const uint8_t kBits_{tag}[] = {{' + ','.join(map(str, bitmap or [0])) + '};')
        out.append(f'static const Glyph kGlyphs_{tag}[] = {{' + ', '.join(glyphs) + '};')
        table.append(f"{{{f['weight']}, {f['size']}, {f['top']}, {f['middle']}, kGlyphs_{tag}, {len(glyphs)}, kBits_{tag}}}")
    out.append('')
    out.append('const Font kFonts[] = {\n    ' + ',\n    '.join(table) + '\n};')
    out.append(f'const int kFontCount = {len(table)};')
    out.append('')
    out.append('}  // namespace ui')
    path = os.path.join(HERE, '..', 'src', 'fonts.cpp')
    with open(path, 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    print(f'font_build: {len(table)} fonts -> {os.path.normpath(path)}')

if __name__ == '__main__':
    main()
