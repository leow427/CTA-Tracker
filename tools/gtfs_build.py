#!/usr/bin/env python3
"""Build the stop list, train sequences, and train shapes from CTA's GTFS feed (plan 1, task 10).

Usage: python3 tools/gtfs_build.py <gtfs.zip or dir> [--check]

Writes data/stops.json, data/train_lines.json, data/train_shapes.json, and
firmware/lib/cta/src/train_sequences.cpp. Standard library only.
"""
import argparse
import csv
import io
import json
import math
import os
import re
import sys
import zipfile
from collections import Counter, defaultdict
from dataclasses import dataclass

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
TRAIN_ROUTES = {"Red", "Blue", "Brn", "G", "Org", "P", "Pink", "Y"}
CHICAGO = (41.6, 42.1, -88.0, -87.5)   # lat min, lat max, lon min, lon max
SIMPLIFY_M = 5
LEAD_IN = 6   # platforms before a line's first stop, so the dock's LED row (6 before mine) works at its start
CONTINUES = 0.9      # a lead-in platform needs this share of its trains to reach the line's first stop
SHARED_TRUNK = 0.8   # headsigns this close to a platform's most common one share its label ("A & B")
BOUNDS = {"North", "South", "East", "West"}
COLORS = "Red|Blue|Brown|Green|Orange|Purple|Pink|Yellow"
LINE_LIST = re.compile(rf"\s*\((?:{COLORS})(?:/(?:{COLORS}))*\)$")


@dataclass
class TrainLine:
    route: str
    dir: str           # the pattern's most common trip_headsign
    stop_ids: list     # platform stop_ids, in order
    names: list        # parent station names
    lead: int = 0      # how many of the first stops are lead-in from before this direction starts


def rows(src, name):
    """Yield dict rows of one GTFS file from a zip or a directory."""
    if os.path.isdir(src):
        with open(os.path.join(src, name), encoding="utf-8-sig", newline="") as f:
            yield from csv.DictReader(f)
    else:
        with zipfile.ZipFile(src) as z, io.TextIOWrapper(z.open(name), encoding="utf-8-sig", newline="") as f:
            yield from csv.DictReader(f)


def station_name(name):
    """Drop a trailing list of line colors ("Belmont (Red/Brown/Purple)" → "Belmont"), the line badge says it.
    Branch notes stay ("Harlem (Blue - Forest Park Branch)"): the Blue Line has two Harlems."""
    return LINE_LIST.sub("", name)


def shared_label(heads):
    """A platform's direction from its stop_headsign counts: the most common, or on a trunk shared by branches
    (Green: Ashland/63rd and Cottage Grove, 177 each) every headsign within SHARED_TRUNK of it, joined
    ("Ashland/63rd & Cottage Grove"), so a near tie never flips with the next feed."""
    top = max(heads.values())
    return " & ".join(sorted(h for h, n in heads.items() if n >= SHARED_TRUNK * top))


def bus_dir(value, trip_id):
    """CTA's non-standard trips.txt `direction` ("North") as Bus Tracker writes it ("Northbound")."""
    if value in BOUNDS:
        return value + "bound"
    if value.endswith("bound") and value[:-5] in BOUNDS:
        return value
    raise ValueError(f"trips.txt: trip {trip_id} has unknown direction {value!r}")


def simplify(points, tolerance_m):
    """Douglas–Peucker on (lat, lon) points, measuring in meters on a local flat projection."""
    if len(points) < 3:
        return list(points)
    lat0 = math.radians(sum(p[0] for p in points) / len(points))
    xy = [(math.radians(p[1]) * math.cos(lat0) * 6_371_000, math.radians(p[0]) * 6_371_000) for p in points]

    def distance(i, a, b):
        (px, py), (ax, ay), (bx, by) = xy[i], xy[a], xy[b]
        dx, dy = bx - ax, by - ay
        if dx == dy == 0:
            return math.hypot(px - ax, py - ay)
        t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
        return math.hypot(px - ax - t * dx, py - ay - t * dy)

    keep = {0, len(points) - 1}
    stack = [(0, len(points) - 1)]
    while stack:   # iterative, so a long shape can't hit the recursion limit
        a, b = stack.pop()
        if b - a < 2:
            continue
        i, d = max(((i, distance(i, a, b)) for i in range(a + 1, b)), key=lambda t: t[1])
        if d > tolerance_m:
            keep.add(i)
            stack += [(a, i), (i, b)]
    return [points[i] for i in sorted(keep)]


class Output:
    def __init__(self, stops, lines, shapes, near_cut=()):
        self.stops, self.lines, self.shapes = stops, lines, shapes
        self.near_cut = list(near_cut)   # platforms whose headsign counts sit near SHARED_TRUNK, so a rebuild could flip them

    def train_lines_json(self):
        return [{"route": l.route, "dir": l.dir,
                 "stops": [{"id": i, "name": n} for i, n in zip(l.stop_ids, l.names)], "lead": l.lead}
                for l in self.lines]

    def cpp(self):
        def s(text):
            return json.dumps(text, ensure_ascii=False)   # a valid C string literal for these names
        out = ["// Generated by tools/gtfs_build.py from CTA's GTFS feed. Do not edit.",
               '#include "train_sequences.h"', "", "namespace cta {", ""]
        for n, l in enumerate(self.lines):
            out.append(f"static const char* const kIds{n}[] = {{{', '.join(map(s, l.stop_ids))}}};")
            out.append(f"static const char* const kNames{n}[] = {{{', '.join(map(s, l.names))}}};")
        out += ["", "const TrainLine kTrainLines[] = {"]
        out += [f"    {{{s(l.route)}, {s(l.dir)}, kIds{n}, kNames{n}, {len(l.stop_ids)}, {l.lead}}},"
                for n, l in enumerate(self.lines)]
        out += ["};", f"const size_t kTrainLineCount = {len(self.lines)};", "", "}  // namespace cta", ""]
        return "\n".join(out)

    def write(self, root=ROOT):
        def dump(rel, text):
            path = os.path.join(root, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
        compact = {"separators": (",", ":"), "ensure_ascii": False}
        dump("data/stops.json", json.dumps(self.stops, **compact) + "\n")
        dump("data/train_lines.json", json.dumps(self.train_lines_json(), **compact) + "\n")
        dump("data/train_shapes.json", json.dumps(self.shapes, **compact) + "\n")
        dump("firmware/lib/cta/src/train_sequences.cpp", self.cpp())


def build(src):
    route_type = {r["route_id"]: r["route_type"] for r in rows(src, "routes.txt")}

    trips = {}
    for t in rows(src, "trips.txt"):
        kind = route_type.get(t["route_id"])
        if kind == "1":
            trips[t["trip_id"]] = ("train", t["route_id"], t["direction_id"], t.get("trip_headsign", ""), t.get("shape_id", ""))
        elif kind == "3":
            if "direction" not in t:
                raise ValueError("trips.txt has no `direction` column; bus directions come from it")
            trips[t["trip_id"]] = ("bus", t["route_id"], bus_dir(t["direction"], t["trip_id"]))

    # One pass over stop_times: train trips feed the sequences, bus trips only each stop's lines.
    train_stops = defaultdict(list)    # trip_id -> [(sequence, stop_id)]
    stop_headsigns = defaultdict(Counter)   # trip_id -> Counter(stop_headsign), for feeds without trip_headsign
    platform_heads = defaultdict(Counter)   # (platform, route) -> Counter(stop_headsign)
    trips_at = defaultdict(set)             # (platform, route) -> train trip_ids stopping there
    bus_lines = defaultdict(set)       # stop_id -> {(route, dir)}
    for st in rows(src, "stop_times.txt"):
        trip = trips.get(st["trip_id"])
        if trip is None:
            continue
        if trip[0] == "train":
            train_stops[st["trip_id"]].append((int(st["stop_sequence"]), st["stop_id"]))
            trips_at[(st["stop_id"], trip[1])].add(st["trip_id"])
            if st.get("stop_headsign"):
                stop_headsigns[st["trip_id"]][st["stop_headsign"]] += 1
                platform_heads[(st["stop_id"], trip[1])][st["stop_headsign"]] += 1
        else:
            bus_lines[st["stop_id"]].add((trip[1], trip[2]))

    stops = {s["stop_id"]: s for s in rows(src, "stops.txt")}

    def name_of(platform_id):
        p = stops.get(platform_id, {})
        return station_name(stops.get(p.get("parent_station") or "", p).get("stop_name", platform_id))

    def best(counter):
        return max(counter.items(), key=lambda kv: (kv[1], kv[0]))[0]   # ties: the larger key, deterministic

    patterns = defaultdict(Counter)    # (route, direction_id) -> Counter(ordered platform tuple)
    pattern_of = {}                    # trip_id -> its pattern
    trips_of = defaultdict(list)       # (route, direction_id, pattern) -> trip_ids
    for trip_id, seq in train_stops.items():
        _, route, direction, _, _ = trips[trip_id]
        pattern = tuple(stop for _, stop in sorted(seq))
        patterns[(route, direction)][pattern] += 1
        pattern_of[trip_id] = pattern
        trips_of[(route, direction, pattern)].append(trip_id)

    labels = {}
    def pattern_label(route, direction, pattern):
        """The pattern's most common trip_headsign; CTA's feed has none, so then its most common stop_headsign."""
        key = (route, direction, pattern)
        if key not in labels:
            ts = trips_of[key]
            heads = Counter(trips[t][3] for t in ts if trips[t][3])
            if not heads:
                for t in ts:
                    heads.update(stop_headsigns[t])
            if not heads:
                raise ValueError(f"{route} direction {direction}: no trip_headsign or stop_headsign to label it")
            labels[key] = best(heads)
        return labels[key]

    # Patterns most common first, per (route, direction_id). Each contributes only its stretches of platforms no
    # earlier pattern of the route covered: that adds the opposite one-way trip CTA files under the same
    # direction_id (Purple, Yellow), Green's second branch, and Purple Express, but nothing for short turns.
    stretches = []                     # (route, direction_id, pattern, start, end)
    covered = defaultdict(set)         # route -> platforms already in a stretch
    for (route, direction), counter in sorted(patterns.items()):
        for pattern, _ in sorted(counter.items(), key=lambda kv: (kv[1], kv[0]), reverse=True):
            i = 0
            while i < len(pattern):
                if pattern[i] in covered[route]:
                    i += 1
                    continue
                j = i
                while j < len(pattern) and pattern[j] not in covered[route]:
                    j += 1
                stretches.append((route, direction, pattern, i, j))
                i = j
            covered[route] |= set(pattern)

    covering = {}                      # (platform, route) -> label of the first pattern whose stretch holds it
    for route, direction, pattern, i, j in stretches:
        for stop in pattern[i:j]:
            covering.setdefault((stop, route), pattern_label(route, direction, pattern))

    def platform_label(stop, route, direction, pattern):
        """A platform's direction: its most common stop_headsign for the route (Train Tracker's destNm), else the
        label of the pattern that first covered it, else its own pattern's. Round trips (Brown: Kimball → Loop →
        Kimball, all one direction_id) need the platform's own label, or both Belmont Brown platforms read "Kimball"."""
        heads = platform_heads.get((stop, route))
        if heads:
            return shared_label(heads)
        return covering.get((stop, route)) or pattern_label(route, direction, pattern)

    def lead_start(route, pattern, i):
        """How far back a piece starting at pattern[i] leads in: up to LEAD_IN platforms, while nearly all of each
        one's trains go on to pattern[i]. Brown's Loop turn keeps 6; Green's branches and the Purple Express
        get none, since most trains on the shared track never reach them."""
        reach = trips_at[(pattern[i], route)]
        k = i
        while k > 0 and i - k < LEAD_IN:
            at = trips_at[(pattern[k - 1], route)]
            if not at or len(at & reach) < CONTINUES * len(at):
                break
            k -= 1
        return k

    # Sequences: each stretch, split where the platform labels change, so a line's direction agrees with
    # stops.json. Each piece leads in with up to LEAD_IN platforms before it, for the dock's approach rows.
    lines, shapes_wanted = [], []      # shapes_wanted: (route, shape_id), each route's first one first
    shape_stations = defaultdict(set)  # route -> stations its wanted shapes pass
    def station_of(platform):
        return stops.get(platform, {}).get("parent_station") or platform

    for route, direction, pattern, start, end in stretches:
        names = [name_of(p) for p in pattern]
        run_labels = [platform_label(p, route, direction, pattern) for p in pattern]
        i = start
        while i < end:
            j = i
            while j < end and run_labels[j] == run_labels[i]:
                j += 1
            first = lead_start(route, pattern, i)
            if j - first > 255:
                raise ValueError(f"{route} {run_labels[i]}: {j - first} stops won't fit TrainLine.count (uint8_t)")
            lines.append(TrainLine(route, run_labels[i], list(pattern[first:j]), names[first:j], i - first))
            i = j
        # Shapes: the route's first stretch gives its main shape (direction 0, or the first direction it has: CTA
        # runs Orange, Pink, Purple, and Yellow in direction 1 only). A later stretch whose pattern reaches stations
        # those shapes miss adds its own (Green's Ashland/63rd branch, the Purple Express trunk to the Loop).
        shape_ids = Counter(trips[t][4] for t in trips_of[(route, direction, pattern)] if trips[t][4])
        new_stations = {station_of(p) for p in pattern[start:end]} - shape_stations[route]
        if shape_ids and new_stations:
            if (route, best(shape_ids)) not in shapes_wanted:
                shapes_wanted.append((route, best(shape_ids)))
            shape_stations[route] |= {station_of(p) for p in pattern}

    platform_lines = defaultdict(set)  # platform -> {(route, label)}
    for trip_id, seq in train_stops.items():
        _, route, direction, _, _ = trips[trip_id]
        for _, stop in seq:
            platform_lines[stop].add((route, platform_label(stop, route, direction, pattern_of[trip_id])))

    def as_lines(pairs):
        return [{"route": r, "dir": d} for r, d in sorted(pairs)]

    def base(s):
        name = station_name(s["stop_name"]) if s.get("location_type") == "1" else s["stop_name"]
        return {"id": s["stop_id"], "name": name,
                "lat": round(float(s["stop_lat"]), 6), "lon": round(float(s["stop_lon"]), 6)}

    platforms = defaultdict(list)
    for pid, s in stops.items():
        if s.get("parent_station") and pid in platform_lines:
            platforms[s["parent_station"]].append({"id": pid, "lines": as_lines(platform_lines[pid])})

    out = []
    for sid, s in stops.items():
        loc = s.get("location_type") or "0"
        if loc == "1" and platforms.get(sid):   # stations with no served platform are left out
            out.append({**base(s), "kind": "station", "platforms": sorted(platforms[sid], key=lambda p: p["id"])})
        # Bus bays can be parented to a station (95th/Dan Ryan, Jefferson Park); a stop is a bus stop by its trips.
        elif loc == "0" and sid not in platform_lines and bus_lines.get(sid):
            out.append({**base(s), "kind": "bus", "lines": as_lines(bus_lines[sid])})
    out.sort(key=lambda s: (s["kind"], s["id"]))

    points = defaultdict(list)
    wanted = {shape_id for _, shape_id in shapes_wanted}
    for p in rows(src, "shapes.txt"):
        if p["shape_id"] in wanted:
            points[p["shape_id"]].append((int(p["shape_pt_sequence"]), float(p["shape_pt_lat"]), float(p["shape_pt_lon"])))
    shapes = []
    for route, shape_id in sorted(shapes_wanted, key=lambda rs: rs[0]):   # stable: a route's main shape first
        path = [(lat, lon) for _, lat, lon in sorted(points[shape_id])]
        shapes.append({"route": route, "points": [[round(a, 5), round(b, 5)] for a, b in simplify(path, SIMPLIFY_M)]})

    near_cut = sorted(f"{route} {stop}" for (stop, route), heads in platform_heads.items()
                      if any(0.7 * max(heads.values()) <= n < 0.9 * max(heads.values()) for n in heads.values()))
    return Output(out, lines, shapes, near_cut)


def check(out):
    """Sanity checks on the real feed (plan 1, task 10, step 5). Returns a list of failures."""
    failures = []
    routes = {l.route for l in out.lines}
    if routes != TRAIN_ROUTES:
        failures.append(f"train routes are {sorted(routes)}, expected {sorted(TRAIN_ROUTES)}")
    south = [l for l in out.lines if l.route == "Red" and "95th" in l.dir]
    if not south:
        failures.append("no Red Line direction labeled 95th")
    else:
        names = south[0].names
        order = [names.index(n) if n in names else -1 for n in ("Belmont", "Fullerton", "Clark/Division")]
        if -1 in order or order != sorted(order):
            failures.append(f"Red 95th order of Belmont, Fullerton, Clark/Division is {order}")
    for route in sorted(TRAIN_ROUTES):
        dirs = {l.dir for l in out.lines if l.route == route}
        if len(dirs) < 2:
            failures.append(f"{route} has directions {sorted(dirs)}, expected both")
    # Every platform's (route, dir) in stops.json is pickable: some sequence with that label holds it (past its lead).
    pickable = {(l.route, l.dir, p) for l in out.lines for p in l.stop_ids[l.lead:]}
    missing = Counter(line["route"] for s in out.stops if s["kind"] == "station" for p in s["platforms"]
                      for line in p["lines"] if (line["route"], line["dir"], p["id"]) not in pickable)
    for route, n in sorted(missing.items()):
        failures.append(f"{n} {route} platform directions in stops.json have no sequence")
    if out.near_cut:
        failures.append(f"{len(out.near_cut)} platform labels near the shared-trunk cut: {', '.join(out.near_cut[:5])}")
    bus = [s for s in out.stops if s["kind"] == "bus"]
    if len(bus) <= 10_000:
        failures.append(f"only {len(bus)} bus stops")
    if any(not s["lines"] for s in bus):
        failures.append("a bus stop has no lines")
    if {s["route"] for s in out.shapes} != TRAIN_ROUTES:
        failures.append(f"train shapes cover {sorted(s['route'] for s in out.shapes)}")
    la0, la1, lo0, lo1 = CHICAGO
    if any(not (la0 <= a <= la1 and lo0 <= b <= lo1) for s in out.shapes for a, b in s["points"]):
        failures.append("a train shape point is outside Chicago")
    size = len(json.dumps(out.shapes, separators=(",", ":")).encode()) + 1
    if size >= 200_000:
        failures.append(f"train_shapes.json is {size} bytes, over 200 KB")
    return failures


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("src", help="GTFS zip or directory")
    ap.add_argument("--check", action="store_true", help="assert the real-feed sanity checks")
    args = ap.parse_args(argv)
    out = build(args.src)
    if args.check:
        failures = check(out)
        for f in failures:
            print("check failed:", f, file=sys.stderr)
        if failures:
            return 1
    out.write()
    bus = sum(s["kind"] == "bus" for s in out.stops)
    print(f"{len(out.stops) - bus} stations, {bus} bus stops, {len(out.lines)} train lines, {len(out.shapes)} shapes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
