"""Builds firmware/lib/cta/src/train_map.cpp: the dock map's L tracks and platform positions.

The tracks are data/train_shapes.json (one simplified path per line run, from gtfs_build.py), the positions each
train platform's station from data/stops.json, for every platform in data/train_lines.json. Coordinates are stored
as fixed point (degrees x 1e5, about 1 m), about 9 KB of flash in all.

Run from the repo root: python3 tools/map_build.py
"""
import argparse
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "firmware", "lib", "cta", "src", "train_map.cpp")


def load(data_dir):
    def read(name):
        with open(os.path.join(data_dir, name)) as fh:
            return json.load(fh)
    return read("train_shapes.json"), read("train_lines.json"), read("stops.json")


def fixed(deg):
    return int(round(deg * 1e5))


def cpp_source(shapes, lines, stops):
    where = {}
    for s in stops:
        for p in s.get("platforms", []):
            where[p["id"]] = (s["lat"], s["lon"])
    platforms = sorted({st["id"] for line in lines for st in line["stops"]})
    missing = [p for p in platforms if p not in where]
    if missing:
        sys.exit(f"map_build: platforms missing from stops.json: {', '.join(missing)}")
    out = ["// Generated by tools/map_build.py from data/train_shapes.json, train_lines.json and stops.json. Do not edit.",
           '#include "train_map.h"', "", "namespace cta {", ""]
    table = []
    for k, sh in enumerate(shapes):
        pts = ", ".join(f"{{{fixed(la)}, {fixed(lo)}}}" for la, lo in sh["points"])
        out.append(f"static const int32_t kShape{k}[][2] = {{{pts}}};")
        table.append(f'{{"{sh["route"]}", kShape{k}, {len(sh["points"])}}}')
    out.append("")
    out.append("const TrainShape kTrainShapes[] = {\n    " + ",\n    ".join(table) + "\n};")
    out.append(f"const size_t kTrainShapeCount = {len(table)};")
    out.append("")
    rows = [f'{{"{p}", {fixed(where[p][0])}, {fixed(where[p][1])}}}' for p in platforms]
    out.append("const PlatformPos kPlatforms[] = {\n    " + ",\n    ".join(rows) + "\n};")
    out.append(f"const size_t kPlatformCount = {len(rows)};")
    out.append("")
    out.append("}  // namespace cta")
    return "\n".join(out) + "\n"


def main():
    argparse.ArgumentParser(description="Writes firmware/lib/cta/src/train_map.cpp from data/.").parse_args()
    src = cpp_source(*load(os.path.join(ROOT, "data")))
    with open(OUT, "w") as fh:
        fh.write(src)
    print(f"map_build: wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
